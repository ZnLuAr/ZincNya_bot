"""
网页读取工具配置。

AFC 工具自带配置，不写入项目根 config.py。本工具没有敏感项，也不读环境变量；
需要调整时直接改本文件的常量。

单次调用的最长耗时约为 超时 ×（重试次数 + 1）+ 退避，要留在 AFC 的单次工具
执行超时（根 config 的 AFC_TOOL_TIMEOUT_SECONDS）以内，否则重试还没跑完就会被
框架按超时记为失败。
"""


# ==============================================================================
# 抓取配置
# ==============================================================================

# 单次 HTTP 请求超时（秒）
WEB_FETCH_TIMEOUT_SECONDS = 6

# 网络错误时的重试次数与退避（秒）
WEB_FETCH_MAX_RETRIES = 1
WEB_FETCH_RETRY_BACKOFF_SECONDS = 0.5

# 最多跟随的 redirect 跳数，每一跳都重新做地址安全校验
WEB_FETCH_REDIRECT_LIMIT = 3

# 响应体读取上限（字节），超出部分不再读取
WEB_FETCH_MAX_BYTES = 512 * 1024


# ==============================================================================
# 输出配置
# ==============================================================================

# 交给模型的正文长度上限（字符）；要小于 AFC_TOOL_RESULT_MAX_CHARS，给地址和标题留出余量
WEB_FETCH_MAX_CHARS = 7000


# ==============================================================================
# 安全配置
# ==============================================================================

# 拒绝访问的 hostname（含其子域）。私有 / 回环 / 链路本地地址另由 IP 校验拦截
WEB_FETCH_BLOCKED_HOSTS = (
    "localhost",
    "metadata",
    "metadata.google.internal",
    "169.254.169.254",
)
